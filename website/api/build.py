"""Generate native Docusaurus API pages from statically parsed Python source."""

from __future__ import annotations

import argparse
import runpy
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
API_SOURCE = Path(__file__).resolve().parent


def main() -> int:
    """Build checked Markdown, then refresh the generated portion of the manual."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.parse_args()
    try:
        import sphinx_markdown_builder  # noqa: F401
        from sphinx.cmd.build import build_main
    except ModuleNotFoundError:
        parser.exit(
            1, "Install documentation dependencies: uv sync --locked --group docs --inexact\n"
        )

    generated = ROOT / "website" / ".generated"
    staged_source = generated / "api" / "source"
    markdown_output = generated / "api" / "markdown"
    manual_output = ROOT / "docs" / "reference" / "api"
    # Remove the former standalone HTML site, including during local migration.
    legacy_html = generated / "site" / "api"
    if legacy_html.exists():
        shutil.rmtree(legacy_html)
    for directory in (staged_source, markdown_output):
        if directory.exists():
            shutil.rmtree(directory)
    shutil.copytree(API_SOURCE / "source", staged_source)
    # The publication scope is the only module registry. Adding a published
    # source file also adds its generated page to Sphinx's temporary toctree.
    published = runpy.run_path(str(API_SOURCE / "scope.py"))["API_MODULES"]
    toctree = ".. toctree::\n   :maxdepth: 1\n\n" + "\n".join(
        "   autoapi/modsim_robotics/" + path.removesuffix(".py") + "/index"
        for path in sorted(published)
    )
    index = staged_source / "index.rst"
    index.write_text(
        index.read_text(encoding="utf-8").replace(".. api-modules::", toctree),
        encoding="utf-8",
    )
    result = build_main(
        [
            "--quiet",
            "-b",
            "markdown",
            "-c",
            str(API_SOURCE),
            "-d",
            str(generated / "api" / "doctrees"),
            "--fresh-env",
            "--fail-on-warning",
            str(staged_source),
            str(markdown_output),
        ]
    )
    if result:
        return result

    modules = markdown_output / "autoapi"
    module_files = sorted(modules.rglob("index.md"))
    if not module_files:
        parser.exit(1, "AutoAPI produced no module Markdown pages.\n")
    prepared = generated / "api" / "manual"
    if prepared.exists():
        shutil.rmtree(prepared)
    for path in module_files:
        relative = path.relative_to(modules)
        module = ".".join(relative.parts[:-1])
        target = prepared / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        # Preserve the builder's relative source links and qualified object IDs.
        # Docusaurus supplies all rendering, theme, navigation, and page layout.
        frontmatter = (
            "---\n"
            f"title: {module.removeprefix('modsim_robotics.')}\n"
            f"sidebar_label: {module.removeprefix('modsim_robotics.')}\n"
            f"slug: /reference/api/{relative.parent.as_posix()}/\n"
            "custom_edit_url: null\n"
            "toc_max_heading_level: 3\n"
            "className: api-reference\n"
            "---\n\n"
            "<!-- Generated from Python source. Edit docstrings and regenerate; "
            "do not edit this file. -->\n\n"
        )
        target.write_text(frontmatter + path.read_text(encoding="utf-8"), encoding="utf-8")
    if manual_output.exists():
        shutil.rmtree(manual_output)
    shutil.copytree(prepared, manual_output)
    print(f"Generated {len(module_files)} native API pages in docs/reference/api/.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
